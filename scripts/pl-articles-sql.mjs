// Builds the SQL that inserts (or updates) the Polish article translations from
// content/articles-pl/<slug>.json. Category, author and images are taken from the Czech
// original, translation_of links the two versions. Safe to run twice.
// New rows are inserted UNPUBLISHED: code deployed before the language split lists every
// published article on kastrup.cz, so publish them only after the PR is live
// (update public.articles set published = true where lang = 'pl').
// Usage: node scripts/pl-articles-sql.mjs > content/articles-pl/insert-pl-articles.sql
import { readdirSync, readFileSync } from 'node:fs';

const dir = new URL('../content/articles-pl/', import.meta.url);
const files = readdirSync(dir).filter((name) => name.endsWith('.json')).sort();

// Dollar quoting with a tag that cannot occur in the text
const quote = (value) => {
  if (value === null || value === undefined || value === '') return 'null';
  const text = String(value);
  let tag = 'pl';
  while (text.includes(`$${tag}$`)) tag += 'x';
  return `$${tag}$${text}$${tag}$`;
};

const required = ['source_slug', 'slug', 'title', 'perex', 'content', 'meta_title', 'meta_description'];
const statements = files.map((name) => {
  const article = JSON.parse(readFileSync(new URL(name, dir), 'utf8'));
  for (const field of required) {
    if (!article[field]) throw new Error(`${name}: missing ${field}`);
  }
  if (!/^[a-z0-9][a-z0-9-]*$/.test(article.slug)) throw new Error(`${name}: invalid slug ${article.slug}`);

  return `-- ${article.slug} (překlad /clanek/${article.source_slug})
insert into public.articles
  (lang, translation_of, slug, title, perex, content, meta_title, meta_description, focus_keyword,
   category_id, author_id, image_url, og_image, published)
select 'pl', cs.id, ${quote(article.slug)}, ${quote(article.title)}, ${quote(article.perex)}, ${quote(article.content)},
       ${quote(article.meta_title)}, ${quote(article.meta_description)}, ${quote(article.focus_keyword)},
       cs.category_id, cs.author_id, cs.image_url, cs.og_image, false
from public.articles cs
where cs.lang = 'cs' and cs.slug = ${quote(article.source_slug)}
on conflict (lang, slug) do update set
  translation_of = excluded.translation_of, title = excluded.title, perex = excluded.perex,
  content = excluded.content, meta_title = excluded.meta_title, meta_description = excluded.meta_description,
  focus_keyword = excluded.focus_keyword, updated_at = now();`;
});

process.stdout.write(`-- Polish translations of kastrup.cz articles for kastrup.pl.
-- Generated by scripts/pl-articles-sql.mjs. Run after 20260928120000_article_languages.sql.
-- Inserted unpublished; publish only after the language-aware code is deployed.
begin;
${statements.join('\n\n')}

-- Every translation must have found its Czech original
do $$
declare missing integer;
begin
  select ${files.length} - count(*) into missing from public.articles where lang = 'pl' and translation_of is not null;
  if missing > 0 then raise exception 'Some Polish articles were not inserted (% missing)', missing; end if;
end $$;
commit;
`);
